import CoreGraphics

/// The corner radii of Bubo, in points.
enum CornerRadius {
    /// Chips and small controls.
    static let small: CGFloat = 8
    /// Rows and buttons.
    static let medium: CGFloat = 10
    /// Cards.
    static let large: CGFloat = 14
    /// Glass panels.
    static let panel: CGFloat = 18
}
